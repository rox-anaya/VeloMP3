-- =====================================================================
-- 001_tables.sql — creates every table the ANVG website uses.
-- Run FIRST, in a fresh Supabase project (SQL Editor > New query > Run).
-- Column names and types match js/admin.js and js/pages/*.js.
-- Safe to re-run ("if not exists").
-- =====================================================================

-- Positions = the roles people hold. Names must match staff_members.role_title exactly.
-- can_manage_access = true lets that position open the Access page.
create table if not exists positions (
  name text primary key,
  can_manage_access boolean not null default false,
  sort_order integer not null default 0
);

-- Staff. Also links a Supabase login (user_id) to a position (role_title).
create table if not exists staff_members (
  id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete set null,
  name text,
  role_title text references positions(name) on update cascade on delete set null,
  department text,
  callsign text,
  icon_class text,
  bio text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

-- Which section each position may EDIT. Managed from the admin Access page.
create table if not exists position_sections (
  position text not null references positions(name) on update cascade on delete cascade,
  section text not null
    check (section in ('home','stats','events','fleet','roster','codeshares','staff','changelog','settings')),
  can_edit boolean not null default false,
  primary key (position, section)
);

-- Home page content. One row, id = 1.
-- global_theme / global_weather are kept only so data from the old v2 site fits.
-- The v3 site does not use them; visitors choose theme and effects themselves.
create table if not exists home_config (
  id bigint primary key,
  va_name text,
  va_tagline text,
  hero_badge text,
  hero_bg_url text,
  logo_url text,
  mission_text text,
  ceo_quote text,
  ceo_name text,
  ceo_role text,
  notam_active boolean not null default false,
  notam_text text,
  notam_color text default '#007fc1',
  global_theme text,
  global_weather text
);

-- Statistics. One row, id = 1. Stored as text, matching the admin input boxes.
create table if not exists statistics (
  id integer primary key,
  total_hours text,
  total_pireps text,
  hubs text,
  aircraft_family text,
  destinations text,
  updated_date text
);

-- Home carousel photos.
create table if not exists showcase (
  id bigint generated by default as identity primary key,
  image_url text not null,
  caption text,
  sort_order integer not null default 0
);

-- Events. Dates are real dates (the admin sends YYYY-MM-DD).
create table if not exists events (
  id bigint generated by default as identity primary key,
  title text,
  image_url text,
  dep_icao text,
  arr_icao text,
  time_zulu text,
  dep_date date,
  arr_date date,
  description text,
  status text default 'Scheduled',
  created_at timestamptz not null default now()
);

-- Fleet. "division" is the airline key: ana, nca, peach or airjapan.
create table if not exists fleet (
  id bigint generated by default as identity primary key,
  name text,
  division text check (division is null or division in ('ana','nca','peach','airjapan')),
  category text,
  image_url text,
  description text,
  created_at timestamptz not null default now()
);

-- Roster (pilots). Hours are numbers so the leaderboard can sort them.
create table if not exists roster (
  id bigint generated by default as identity primary key,
  pilot_name text,
  callsign text,
  hours numeric(12,2) not null default 0,
  rank_title text default 'Trainee',
  created_at timestamptz not null default now()
);

-- Codeshare partner airlines.
create table if not exists codeshares (
  id bigint generated by default as identity primary key,
  va_name text,
  network_tag text,
  status text,
  hubs text,
  approved_fleet text,
  description text,
  created_at timestamptz not null default now()
);

-- Changelog entries.
create table if not exists changelog (
  id bigint generated by default as identity primary key,
  type text,
  version text,
  title text,
  image_url text,
  external_link text,
  description text,
  created_at timestamptz not null default now()
);

-- Small key/value settings (theme default, effects, voice welcome lines).
create table if not exists site_settings (
  key text primary key,
  value text,
  updated_at timestamptz not null default now()
);
